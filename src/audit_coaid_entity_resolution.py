        strong_groups = strong.groups()
        for pair in pairs:
            pair["weak_link_between_strong_groups"] = bool(pair["original_clear_edge"] and strong.find(pair["left_member_uid"]) != strong.find(pair["right_member_uid"]))
            pair["weak_single_edge_bridge"] = pair["weak_link_between_strong_groups"] and pair["is_original_graph_bridge"]
