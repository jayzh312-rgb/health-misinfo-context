def review_sample(validation, members, pairs):
    selected, reasons = set(), defaultdict(set)
    strata = {
        "very_large_ge10": validation.member_count.ge(10),
        "top20_post_component": validation.priority_top20_post_component,
        "all_fake_components": validation.veracity.eq("fake"),
        "all_ambiguous_or_overmerged": validation.validation_category.isin(CATEGORIES[2:]),
    }
    for name, mask in strata.items():
        for eid in validation.loc[mask, "entity_uid"]:
            selected.add(eid)
            reasons[eid].add(name)
    rng = np.random.default_rng(SEED)
    for name, mask in [("probable", validation.validation_category.eq(CATEGORIES[1])),
                       ("medium_3_to9", validation.member_count.between(3, 9)),
                       ("small_high_confidence", validation.member_count.eq(2) & validation.validation_category.eq(CATEGORIES[0]))]:
        candidates = sorted(set(validation.loc[mask, "entity_uid"]) - selected)
        for eid in rng.permutation(candidates)[:max(0, min(6, 45-len(selected)))]:
            selected.add(eid)
            reasons[eid].add(name)
    remaining = sorted(set(validation.entity_uid) - selected)
    for eid in rng.permutation(remaining)[:max(0, 45-len(selected))]:
        selected.add(eid)
        reasons[eid].add("remaining_stratified_fill")
    assert 30 <= len(selected) <= 50
    rows = []
    for row in validation.loc[validation.entity_uid.isin(selected)].sort_values(["member_count", "total_unique_posts"], ascending=False).to_dict("records"):
        eid = row["entity_uid"]
        pair = max(pairs[eid], key=lambda p: (p["clear_item_conflict"], p["weak_link_between_strong_groups"], bool(p["suspect_original_rule"])))
        left, right = members[pair["left_member_uid"]], members[pair["right_member_uid"]]
        rows.append({**row, "review_selection_reasons": " | ".join(sorted(reasons[eid])),
                     "left_representative_json": js(brief(left)), "right_representative_json": js(brief(right)),
                     "left_text_excerpt": left["text"][:600], "right_text_excerpt": right["text"][:600],
                     "representative_pair_link_reason": pair["link_reason"],
                     "representative_pair_is_original_edge": pair["original_clear_edge"],
                     "representative_pair_risk": pair["suspect_original_rule"],
                     "human_validation_category": "", "human_notes": "", "review_status": "PENDING HUMAN REVIEW"})
    return pd.DataFrame(rows)


def consequences(validation, entity_ids, primary):
    rows = []
    for category in [*CATEGORIES, "COMBINED AMBIGUOUS OR OVER-MERGED"]:
        part = validation.loc[validation.validation_category.isin(CATEGORIES[2:])] if category.startswith("COMBINED") else validation.loc[validation.validation_category.eq(category)]
        for veracity in ("all", "fake", "real"):
            subset = part if veracity == "all" else part.loc[part.veracity.eq(veracity)]
            ids = subset.entity_uid.tolist()
            post_union = set().union(*(entity_ids[e][0] for e in ids))
            reply_union = set().union(*(entity_ids[e][1] for e in ids))
            rows.append({"validation_category": category, "veracity": veracity,
                         "components": len(subset), "percent_of_200_components": 100*len(subset)/200,
                         "source_rows": int(subset.member_count.sum()),
                         "sum_entity_unique_posts": int(subset.total_unique_posts.sum()),
                         "sum_entity_unique_replies": int(subset.total_unique_replies.sum()),
                         "globally_unique_affected_post_ids": len(post_union), "globally_unique_affected_reply_ids": len(reply_union),
                         "share_total_coaid_post_engagement": subset.total_unique_posts.sum()/primary.unique_post_count.sum(),
                         "share_total_coaid_reply_engagement": subset.total_unique_replies.sum()/primary.unique_reply_count.sum(),
                         "notes": "Engagement shares use sum of within-entity unique counts, matching existing primary totals; union-ID counts additionally de-duplicate across affected entities. Affected means contained, not proven erroneous counts or posts to discard."})
    return pd.DataFrame(rows)


def md_table(frame):
    columns = list(frame.columns)
    def cell(x):
        if isinstance(x, float):
            return f"{x:.4g}"
        return str(x).replace("|", "\\|").replace("\n", " ")
    return "\n".join(["| " + " | ".join(columns) + " |", "| " + " | ".join(["---"]*len(columns)) + " |"] +
                     ["| " + " | ".join(cell(v) for v in row) + " |" for row in frame.itertuples(index=False, name=None)])


