def require(condition, message):
    if not condition:
        raise ValueError(message)


def js(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def stable(prefix, items):
    return prefix + hashlib.sha256(js(sorted(items)).encode()).hexdigest()[:24]


def normalize(value):
    # Casefold is only a placeholder check; returned lexical content is unchanged.
    text = re.sub(r"\s+", " ", str(value)).strip()
    return "" if text.strip('"\'').strip().casefold() in NULLS else text


def combine(title, body):
    return SEPARATOR.join(x for x in (title, body) if x)


def quality(text, field):
    """Transparent obvious-crawl-artifact flags, not semantic misinformation rules."""
    if not text:
        return "empty"
    s = text.strip('"\'').casefold()
    exact = {"are you a robot?", "404 not found", "403 forbidden", "page not found", "access denied",
             "log in or sign up to view", "facebook", "video news", "know your value",
             "outlook, office, skype, bing, breaking news, and latest videos"}
    if s in exact:
        return "clear_crawl_artifact"
    markers = ("access denied |", "this website is using security service to protect itself",
               "this website is using a security service to protect itself", "please make sure your browser supports javascript",
               "you are using an older browser version", "javascript is disabled in your browser",
               "this browser is no longer supported", "you must log in to continue", "do you want to join facebook",
               "join this group to post and comment", "we ca nt seem to find the page", "generated by mod_security",
               "generated by mod security", "enjoy the videos and music you love upload original content")
    if len(text) <= 650 and any(marker in s for marker in markers):
        return "clear_crawl_artifact"
    if field == "body" and len(s.split()) <= 40 and "cdc twenty four seven" in s and "saving lives protecting people" in s:
        return "clear_crawl_artifact"
    return "not_flagged"


def save(name, rows, directory=TABLES):
    frame = rows if isinstance(rows, pd.DataFrame) else pd.DataFrame(rows)
    directory.mkdir(parents=True, exist_ok=True)
    frame.to_csv(directory / (name + ".csv"), index=False)
    return frame


def article_host(url):
    return urlsplit(url if "://" in url else "https://" + url).netloc.lower().removeprefix("www.") if url else ""


