def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keep-artifact-only", action="store_true")
    args = parser.parse_args()
    frames, hashes = load_cohorts(args.keep_artifact_only)
    print("Loaded text and label/provenance metadata only; engagement columns excluded.", flush=True)
    audit, edges, overlaps, joins = build_groups(frames)
    summary = cohort_summary(frames)
    sources, association = source_audit(frames)
    summaries = []
    for dataset, frame in frames.items():
        holdout, cv, outer, split_summary = split_plan(dataset, frame)
        again = split_plan(dataset, frame.sample(frac=1, random_state=19))
        pd.testing.assert_frame_equal(holdout, again[0]); pd.testing.assert_frame_equal(cv, again[1])
        prefix = PREFIXES[dataset]
        save(prefix+"_text_holdout", holdout, SPLITS)
        save(prefix+"_text_grouped_cv", cv, SPLITS)
        save(prefix+"_text_outer_partition_provenance", outer, SPLITS)
        summaries.append(split_summary)
        # Defensive allowlist: all cohort fields were explicitly constructed above.
        require(not any("engagement" in c or "post_count" in c or "reply_count" in c or "retweet" in c for c in frame.columns), "Engagement field leaked into text cohort")
        save(prefix+"_text_primary", frame, ROOT / "data/processed")
        print(f"{dataset}: {len(frame)} retained rows; {frame.primary_text_eligible.sum()} eligible; {frame.loc[frame.primary_text_eligible,'leakage_group'].nunique()} eligible groups", flush=True)
    split_summary = pd.concat(summaries, ignore_index=True)
    transfer, transfer_manifest = transfer_plans(frames)
    outputs = {"text_cohort_summary": summary, "text_leakage_group_audit": audit, "text_leakage_edge_audit": edges,
               "text_cross_dataset_overlap_audit": overlaps, "text_source_label_audit": sources,
               "text_source_label_association": association, "text_near_duplicate_method_audit": joins,
               "text_split_summary": split_summary, "text_transfer_plan_summary": transfer_manifest}
    for name, data in outputs.items():
        save(name, data)
    save("text_cross_context_transfer_assignments", transfer, SPLITS)
    write_report(summary, audit, overlaps, association, split_summary, joins, args.keep_artifact_only, edges)
    for relative, expected in hashes.items():
        require(sha(ROOT/relative) == expected, "Input changed: "+relative)
    metadata = dict(input_sha256=hashes, script_sha256=sha(Path(__file__)), seed=42,
                    artifact_only_excluded_from_primary_splits=not args.keep_artifact_only,
                    feature_allowlist=FEATURE_ALLOWLIST, forbidden_predictors="All other fields; especially labels/ratings, IDs, publishers, provenance, quality flags, folds and overlap flags",
                    model_or_vectorizer_fitted=False, engagement_features_imported=False,
                    deterministic_split_check_passed=True, source_inputs_unchanged=True,
                    normalization="Whitespace plus obvious null placeholders only; punctuation and case preserved", separator=repr(SEPARATOR),
                    holdout_protocol="Fixed grouped test; training-only inner CV; fold=-1 never included in CV",
                    cross_dataset_overlap_automatic_exclusion=False)
    metadata["library_versions"] = dict(pandas=pd.__version__, numpy=np.__version__, scikit_learn=sklearn.__version__)
    (TABLES/"text_cohort_preparation_metadata.json").write_text(json.dumps(metadata, indent=2, sort_keys=True)+"\n")
    print(summary[["dataset", "scope", "total_rows", "fake_rows", "real_rows", "nonempty_body", "title_only", "leakage_groups"]].to_string(index=False))
    print(split_summary.to_string(index=False))


if __name__ == "__main__":
    main()
