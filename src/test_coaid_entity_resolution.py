"""Regression checks for identity evidence, capture errors, and graph bridges."""
import unittest

from audit_coaid_entity_resolution import (
    CATEGORIES, annotate_members, bridges, classify, normalize_text,
    pair_evidence, specific_url, text_error, tokens, url_key,
)


def member(uid, url, title, source, body, fact="cdc.gov"):
    body, title = normalize_text(body), normalize_text(title)
    return {"member_uid": uid, "release": "05-01-2020", "original_id": uid,
            "title": title, "normalized_title": title, "source_title": source,
            "normalized_source_title": normalize_text(source), "text": body, "normalized_text": body,
            "news_url": url, "news_url_key": url_key(url), "specific_news_url": specific_url(url_key(url)),
            "fact_check_url": fact, "fact_check_url_key": url_key(fact), "specific_fact_check_url": specific_url(url_key(fact)),
            "generic_title": True, "boilerplate_text": text_error(body), "informative_text": False,
            "posts": set(), "replies": set(), "source_tokens": tokens(normalize_text(source)),
            "text_tokens": tokens(body), "title_tokens": tokens(title)}


class EntityResolutionChecks(unittest.TestCase):
    def test_conservative_url_identity(self):
        self.assertEqual(url_key("https://WWW.example.com/Story?id=2&utm_source=x#comments"), "example.com/Story?id=2")
        self.assertNotEqual(url_key("https://example.com/Story?id=2"), url_key("https://example.com/story?id=2"))
        self.assertNotEqual(url_key("https://example.com/story?id=2"), url_key("https://example.com/story?id=3"))
        self.assertFalse(specific_url(url_key("cdc.gov")))
        self.assertEqual(url_key("https://twitter.com/a/status/123?s=20"), url_key("https://twitter.com/b/status/123"))
        self.assertNotEqual(url_key("https://facebook.com/photo.php?fbid=1"), url_key("https://facebook.com/photo.php?fbid=2"))

    def test_mod_security_is_not_article_identity(self):
        body = "An appropriate representation of the requested resource could not be found on this server. This error was generated by mod_security."
        a = member("a", "https://example.com/5g-study", "Not Acceptable!", "A study links 5G to disease", body)
        b = member("b", "https://elsewhere.com/vaccine-story", "Not Acceptable!", "Romania developed a vaccine for white people", body)
        old = {"classification": "clear duplicate/re-observation", "matching_evidence": "title_exact | content_text_exact"}
        p = pair_evidence(a, b, old)
        self.assertTrue(text_error(normalize_text(body)))
        self.assertFalse(p["validated_strong_pair"])
        self.assertTrue(p["clear_item_conflict"])
        self.assertEqual(classify([a, b], [p], [["a"], ["b"]])[0], CATEGORIES[4])

    def test_domain_and_generic_title_cannot_unify_press_releases(self):
        a = member("a", "https://cdc.gov/media/releases/2020/a.html", "Coronavirus Disease 2019", "School opening guidance", "")
        b = member("b", "https://cdc.gov/media/releases/2020/b.html", "Coronavirus Disease 2019", "Cruise ship order", "")
        p = pair_evidence(a, b, {"classification": "clear duplicate/re-observation", "matching_evidence": "title_exact | fact_check_url_exact"})
        self.assertFalse(p["validated_strong_pair"])
        self.assertTrue(p["factcheck_match_is_domain_only"])
        self.assertTrue(p["clear_item_conflict"])

    def test_social_overlap_is_never_identity_alone(self):
        a = member("a", "https://example.com/a", "a title", "a description", "")
        b = member("b", "https://example.com/b", "b title", "b description", "")
        a["posts"] = b["posts"] = {"123", "456"}
        p = pair_evidence(a, b, {})
        self.assertEqual(p["shared_post_count"], 2)
        self.assertFalse(p["validated_strong_pair"])

    def test_translation_candidate_is_ambiguous(self):
        a = member("a", "https://example.com/articles/coronavirus-causes", "Coronavirus causes", "Origin", "")
        b = member("b", "https://example.com/articles/es/coronavirus-causes-6", "Coronavirus causes", "How it spreads", "")
        p = pair_evidence(a, b, {"classification": "clear duplicate/re-observation", "matching_evidence": "title_exact | fact_check_url_exact"})
        self.assertTrue(p["possible_translation_variant"])
        self.assertEqual(classify([a, b], [p], [["a"], ["b"]])[0], CATEGORIES[2])

    def test_cut_edge_differs_from_redundant_weak_cutset(self):
        self.assertEqual(bridges(["a", "b", "c"], [("a", "b"), ("b", "c")]), {("a", "b"), ("b", "c")})
        self.assertEqual(bridges(["a", "b", "c"], [("a", "b"), ("b", "c"), ("a", "c")]), set())


if __name__ == "__main__":
    unittest.main()
